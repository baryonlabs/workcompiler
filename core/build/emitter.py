    cand = candidate.to_dict() if hasattr(candidate, "to_dict") else dict(candidate)
    samples = cand.get("dataset", {}).get("samples") or cand.get("dataset", {}).get("examples") or []
    n = _jsonl(pkg / "dataset.jsonl", samples)
    cand_yaml = dict(cand)
    cand_yaml["dataset"] = {**{k: v for k, v in cand.get("dataset", {}).items() if k not in ("samples", "examples")},
                            "path": "dataset.jsonl", "num_samples": n}
