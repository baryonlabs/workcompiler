GENERATED_BANNER = "generated by OpenWorkCompiler build emitter (core/build) — edit freely, regenerate with care"


@dataclass
class BuildArtifact:
    action: str
    tier: str
    kind: str
    path: str
    synthesized: bool = False       # content the agent computed itself; must escalate when inputs change
    synthesized_literals: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {"action": self.action, "tier": self.tier, "kind": self.kind, "path": self.path}
        if self.synthesized:
            d["synthesized"] = True
            d["synthesized_literals"] = self.synthesized_literals
        return d


@dataclass
class BuildManifest:
    work: str
    build_dir: str
    artifacts: List[BuildArtifact] = field(default_factory=list)

    params: List[Parameter] = field(default_factory=list)

    def add(self, action: str, tier: str, kind: str, path: Path, root: Path,
            synthesized: bool = False, literals: Optional[List[str]] = None) -> None:
        self.artifacts.append(BuildArtifact(action, tier, kind, str(path.relative_to(root)), synthesized, literals or []))

    def by_tier(self) -> Dict[str, List[str]]:
        out: Dict[str, List[str]] = {}
        for a in self.artifacts:
            out.setdefault(a.tier, []).append(a.path)
        return out

    def to_dict(self) -> Dict[str, Any]:
        return {
            "work": self.work,
            "build_dir": self.build_dir,
            "artifact_count": len(self.artifacts),
            "by_tier": self.by_tier(),
            "params": [p.to_dict() for p in self.params],
            "synthesized_actions": sorted({a.action for a in self.artifacts if a.synthesized}),
            "artifacts": [a.to_dict() for a in self.artifacts],
        }


# --------------------------------------------------------------------------- helpers

def _slug(name: str) -> str:
    return re.sub(r"[^\w]+", "_", name).strip("_").lower() or "action"


def _normalize(name: str) -> str:
    # Mirrors WorkCompiler._normalize_action_name closely enough for grouping trace steps.
    from core.compiler.compiler import WorkCompiler

    return WorkCompiler._normalize_action_name(WorkCompiler.__new__(WorkCompiler), name)


def _examples_by_action(traces: Optional[Iterable[TraceIR]]) -> Dict[str, List[TraceStep]]:
    grouped: Dict[str, List[TraceStep]] = {}
    for trace in traces or []:
        for step in trace.steps:
            if step.action:
                grouped.setdefault(_normalize(step.action), []).append(step)
    return grouped


def _as_dict(value: Any) -> Dict[str, Any]:
    if value is None:
        return {}
    if hasattr(value, "model_dump"):
        value = value.model_dump()
    return value if isinstance(value, dict) else {"value": value}


def _example_io(steps: Sequence[TraceStep]) -> tuple[Dict[str, Any], Dict[str, Any]]:
    if not steps:
        return {}, {}
    return _as_dict(steps[0].input), _as_dict(steps[0].output)


def _relativize_patch(patch: str) -> str:
    """Rewrite absolute file paths under the workspace to relative ones (portable builds)."""
    import os

    roots = [str(Path.cwd().resolve()) + "/"]
    ws = os.environ.get("OPENWORKCOMPILER_WORKSPACE_DIR")
    if ws:
        roots.append(str(Path(ws).resolve()) + "/")
    for root in roots:
        patch = patch.replace(root, "")
    return patch


def _shell_commands(example_input: Dict[str, Any]) -> List[str]:
    """All shell commands a recorded step ran (Codex may batch several per tool call)."""
    cmds = example_input.get("cmds")
    if isinstance(cmds, list) and cmds:
        return [str(c) for c in cmds]
    cmd = example_input.get("cmd") or example_input.get("command")
    if isinstance(cmd, list) and cmd:
        return [" ".join(shlex.quote(str(c)) for c in cmd)]
    return [cmd] if isinstance(cmd, str) and cmd.strip() else []


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _jsonl(path: Path, rows: Iterable[Dict[str, Any]]) -> int:
    rows = list(rows)
    _write(path, "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    return len(rows)


