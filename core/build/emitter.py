def _emit_prompt(root: Path, action: str, executor: Dict[str, Any], steps: Sequence[TraceStep], work: str, invariants: Sequence[str]) -> Path:
    example_in, example_out = _example_io(steps)
    inv = "\n".join(f"- {i}" for i in invariants) or "- (none declared)"
    example = ""
    if example_in or example_out:
        example = f"""
## Recorded example

Input:

```json
{json.dumps(example_in, ensure_ascii=False, indent=2)}
```

Output:

```json
{json.dumps(example_out, ensure_ascii=False, indent=2)}
```
"""
    content = f"""# {action} — frontier LLM prompt contract (work '{work}')

<!-- {GENERATED_BANNER} -->

- preferred model: `{executor.get('preferred') or 'frontier_llm'}`
- fallback: `{executor.get('fallback') or ['human']}`

## System prompt

You execute the action `{action}` of the OpenWorkflow work `{work}`.
Return a JSON object with the output fields shown in the recorded example.
Do not invent data outside the provided inputs. Escalate to a human when uncertain.

## Invariants (must hold)

{inv}
{example}"""
    path = root / "prompts" / f"{action}.prompt.md"
    _write(path, content)
    return path


def _emit_human(root: Path, action: str, executor: Dict[str, Any], work: str, invariants: Sequence[str]) -> Path:
    inv = "\n".join(f"- [ ] {i}" for i in invariants) or "- [ ] output reviewed"
    content = f"""# {action} — human review checklist (work '{work}')

<!-- {GENERATED_BANNER} -->

Reviewer confirms before the workflow may continue:

{inv}
- [ ] decision recorded (approve / reject / request changes)
"""
    path = root / "human" / f"{action}.review.md"
    _write(path, content)
    return path


# --------------------------------------------------------------------------- public API

def emit_build(
    work_ir: WorkIR,
    build_root: Path | str = "build",
    traces: Optional[Iterable[TraceIR]] = None,
    training_candidates: Optional[Dict[str, TrainingCandidate]] = None,
    linkml_yaml: Optional[str] = None,
) -> BuildManifest:
    """Lower ``work_ir`` into ``<build_root>/<work>/`` and return the manifest."""
    root = Path(build_root) / _slug(work_ir.work)
    root.mkdir(parents=True, exist_ok=True)
    manifest = BuildManifest(work=work_ir.work, build_dir=str(root))
    traces = list(traces or [])
    examples = _examples_by_action(traces)
    invariants = list(work_ir.invariants or [])
    candidates = training_candidates or {}
    work_dict = work_ir.to_dict()

    save_work_ir(work_ir, root / "work.yaml")
    manifest.add("*", "work_ir", "work.yaml", root / "work.yaml", root)

    (root / "handlers").mkdir(exist_ok=True)
    _write(root / "handlers" / "__init__.py", f'"""Code-tier handlers for work \'{work_ir.work}\'. {GENERATED_BANNER}"""\n')

    for action in work_ir.actions:
        executor = _as_dict(work_dict.get("executors", {}).get(action, {}))
        tier = str(executor.get("type") or ExecutorType.FRONTIER_LLM.value)
        steps = examples.get(action, [])

        if tier == ExecutorType.CODE.value:
            manifest.add(action, tier, "handler", _emit_code_handler(root, action, executor, steps, work_ir.work), root)
        elif tier == ExecutorType.RULE.value:
            manifest.add(action, tier, "rule", _emit_rule(root, action, executor, steps, work_ir.work, work_ir.inputs), root)
        elif tier == ExecutorType.HTTP.value:
            manifest.add(action, tier, "http", _emit_http(root, action, executor, steps, work_ir.work), root)
        elif tier == ExecutorType.ML.value:
            for p in _emit_ml(root, action, executor, steps, work_ir.work):
                manifest.add(action, tier, p.name, p, root)
        elif tier == ExecutorType.SLM.value:
            for p in _emit_slm(root, action, executor, steps, work_ir.work, candidates.get(action), invariants):
                manifest.add(action, tier, p.name, p, root)
        elif tier == ExecutorType.HUMAN.value:
            manifest.add(action, tier, "review", _emit_human(root, action, executor, work_ir.work, invariants), root)
        else:  # frontier_llm and anything unknown
            manifest.add(action, tier, "prompt", _emit_prompt(root, action, executor, steps, work_ir.work, invariants), root)

    if traces:
        trace_path = root / "trace.json"
        payload = {"traces": [t.model_dump(mode="json") for t in traces]}
        _write(trace_path, json.dumps(payload, indent=2, ensure_ascii=False, default=str) + "\n")
        manifest.add("*", "trace", "trace.json", trace_path, root)

    if linkml_yaml:
        p = root / "schema" / f"{_slug(work_ir.work)}.linkml.yaml"
        _write(p, linkml_yaml)
        manifest.add("*", "schema", "linkml", p, root)

    _write(root / "MANIFEST.json", json.dumps(manifest.to_dict(), indent=2, ensure_ascii=False) + "\n")
    return manifest
