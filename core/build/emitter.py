"""Emit an executable artifact tree from a Work IR (the compiler *backend*).

``work.yaml`` only says *which* executor tier runs each action. The build tree makes
that concrete — one artifact family per tier::

    build/<work>/
    ├── work.yaml                          # Work IR (source of truth for the runtime)
    ├── MANIFEST.json                      # action -> tier -> artifact index
    ├── handlers/<action>.py               # code   : def run(**inputs) -> dict
    ├── rules/<action>.rule.yaml           # rule   : declarative branch list for RuleExecutor
    ├── http/<action>.http.yaml            # http   : request template for HTTPExecutor
    ├── models/ml/<action>/                # ml     : model_card.yaml + dataset.jsonl + train.py
    ├── models/slm/<action>/               # slm    : training_candidate.yaml + dataset.jsonl + train.py
    ├── prompts/<action>.prompt.md         # frontier_llm : prompt contract + recorded examples
    ├── human/<action>.review.md           # human  : review checklist
    └── schema/<work>.linkml.yaml          # optional LinkML schema (OpenWorkLang builds)

Every generated file carries a header naming its origin so hand edits are obvious.
Recorded trace steps (when available) become executable defaults: a code handler
re-runs the captured shell command, datasets are filled with real input/output pairs,
and prompt contracts embed the observed example.
"""

