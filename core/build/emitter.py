"""Emit an executable artifact tree from a Work IR (the compiler *backend*).

``work.yaml`` only says *which* executor tier runs each action. The build tree makes
that concrete — one artifact family per tier::

    build/<work>/
    ├── work.yaml                          # Work IR (source of truth for the runtime)
    ├── MANIFEST.json                      # action -> tier -> artifact index
    ├── handlers/<action>.py               # code   : def run(**inputs) -> dict
    ├── rules/<action>.rule.yaml           # rule   : declarative branch list for RuleExecutor
    ├── http/<action>.http.yaml            # http   : request template for HTTPExecutor
    ├── models/ml/<action>/                # ml     : model_card.yaml + dataset.jsonl + train.py
    ├── models/slm/<action>/               # slm    : training_candidate.yaml + dataset.jsonl + train.py
    ├── prompts/<action>.prompt.md         # frontier_llm : prompt contract + recorded examples
    ├── human/<action>.review.md           # human  : review checklist
    └── schema/<work>.linkml.yaml          # optional LinkML schema (OpenWorkLang builds)

Every generated file carries a header naming its origin so hand edits are obvious.
Recorded trace steps (when available) become executable defaults: a code handler
re-runs the captured shell command, datasets are filled with real input/output pairs,
and prompt contracts embed the observed example.
"""

from __future__ import annotations

import json
import re
import shlex
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence

import yaml

from core.optimizer.optimizer import TrainingCandidate
from core.work_ir import ExecutorType, TraceIR, TraceStep, WorkIR, save_work_ir

GENERATED_BANNER = "generated by OpenWorkflow build emitter (core/build) — edit freely, regenerate with care"


@dataclass
class BuildArtifact:
    action: str
    tier: str
    kind: str
    path: str

    def to_dict(self) -> Dict[str, str]:
        return {"action": self.action, "tier": self.tier, "kind": self.kind, "path": self.path}


@dataclass
class BuildManifest:
    work: str
    build_dir: str
    artifacts: List[BuildArtifact] = field(default_factory=list)

    def add(self, action: str, tier: str, kind: str, path: Path, root: Path) -> None:
        self.artifacts.append(BuildArtifact(action, tier, kind, str(path.relative_to(root))))

    def by_tier(self) -> Dict[str, List[str]]:
        out: Dict[str, List[str]] = {}
        for a in self.artifacts:
            out.setdefault(a.tier, []).append(a.path)
        return out

    def to_dict(self) -> Dict[str, Any]:
        return {
            "work": self.work,
            "build_dir": self.build_dir,
            "artifact_count": len(self.artifacts),
            "by_tier": self.by_tier(),
            "artifacts": [a.to_dict() for a in self.artifacts],
        }


# --------------------------------------------------------------------------- helpers

def _slug(name: str) -> str:
    return re.sub(r"[^\w]+", "_", name).strip("_").lower() or "action"


def _normalize(name: str) -> str:
    # Mirrors WorkCompiler._normalize_action_name closely enough for grouping trace steps.
    from core.compiler.compiler import WorkCompiler

    return WorkCompiler._normalize_action_name(WorkCompiler.__new__(WorkCompiler), name)


def _examples_by_action(traces: Optional[Iterable[TraceIR]]) -> Dict[str, List[TraceStep]]:
    grouped: Dict[str, List[TraceStep]] = {}
    for trace in traces or []:
        for step in trace.steps:
            if step.action:
                grouped.setdefault(_normalize(step.action), []).append(step)
    return grouped


def _as_dict(value: Any) -> Dict[str, Any]:
    if value is None:
        return {}
    if hasattr(value, "model_dump"):
        value = value.model_dump()
    return value if isinstance(value, dict) else {"value": value}


def _example_io(steps: Sequence[TraceStep]) -> tuple[Dict[str, Any], Dict[str, Any]]:
    if not steps:
        return {}, {}
    return _as_dict(steps[0].input), _as_dict(steps[0].output)


def _shell_commands(example_input: Dict[str, Any]) -> List[str]:
    """All shell commands a recorded step ran (Codex may batch several per tool call)."""
    cmds = example_input.get("cmds")
    if isinstance(cmds, list) and cmds:
        return [str(c) for c in cmds]
    cmd = example_input.get("cmd") or example_input.get("command")
    if isinstance(cmd, list) and cmd:
        return [" ".join(shlex.quote(str(c)) for c in cmd)]
    return [cmd] if isinstance(cmd, str) and cmd.strip() else []


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _jsonl(path: Path, rows: Iterable[Dict[str, Any]]) -> int:
    rows = list(rows)
    _write(path, "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    return len(rows)


