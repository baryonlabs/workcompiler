def _emit_rule(root: Path, action: str, executor: Dict[str, Any], steps: Sequence[TraceStep], work: str,
               work_inputs: Sequence[str] = ()) -> Path:
    example_in, example_out = _example_io(steps)
    fields = [k for k in example_in.keys() if not k.startswith("__")] or list(work_inputs) or ["input"]
    spec = {
        "action": action,
        "handler": executor.get("handler") or f"rules.{action}",
        "description": f"Declarative rule branches for '{action}' (work '{work}'). "
                       "Evaluated top-down by RuleExecutor; first match wins unless stop_on_match: false.",
        "rules": [
            {
                "name": f"{action}_default",
                "when": [{"field": fields[0], "op": "exists"}],
                "then": example_out or {"matched": True, "action": action},
                "stop_on_match": True,
            }
        ],
    }
    path = root / "rules" / f"{action}.rule.yaml"
    _write(path, f"# {GENERATED_BANNER}\n" + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True))
    return path


def _emit_http(root: Path, action: str, executor: Dict[str, Any], steps: Sequence[TraceStep], work: str) -> Path:
    example_in, _ = _example_io(steps)
    spec = {
        "action": action,
        "handler": executor.get("handler") or f"connectors.{action}",
        "request": {
            "method": "POST",
            "url": "https://example.invalid/{action}".replace("{action}", action),
            "headers": {"Content-Type": "application/json"},
            "body_template": {k: f"{{{k}}}" for k in example_in.keys() if not k.startswith("__")},
        },
        "retry": {"max_attempts": 3, "backoff_seconds": 2},
    }
    path = root / "http" / f"{action}.http.yaml"
    _write(path, f"# {GENERATED_BANNER}\n" + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True))
    return path


